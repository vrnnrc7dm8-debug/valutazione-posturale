import { test, expect, type Page } from '@playwright/test'
import { readFile, mkdir, writeFile, readdir, rename } from 'node:fs/promises'
import path from 'node:path'
import { createHash } from 'node:crypto'
import { unzipSync, unzlibSync } from 'fflate'

const headers = { 'X-Clinical-App': '1' }
const root = process.env.POSTURAL_E2E_ROOT || '/private/tmp/.postural-e2e-local'
async function api(page: Page, endpoint: string) {
  const response = await page.request.get('/api/' + endpoint, { headers })
  expect(response.ok()).toBeTruthy()
  return response.json()
}
async function search(page: Page, code: string) {
  await page.getByRole('tab', { name: 'Archivio', exact: true }).click()
  await page.getByRole('textbox', { name: 'Cerca paziente', exact: true }).fill(code)
  await page.getByRole('button', { name: 'Cerca / Elenca' }).click()
  await page.getByRole('list', { name: 'Elenco pazienti' }).getByRole('button').filter({ hasText: code }).click()
}

